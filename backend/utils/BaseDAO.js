import getPool from "../configs/db.js";
import {
    DatabaseError,
    ConflictError,
    NotFoundError,
    ValidationError,
} from "./errors.js";

/**
 * This is the base class for all DAOs.
 * @class
 * @abstract
 * @see {@link https://oneuptime.com/blog/post/2026-03-31-mysql-nodejs-mysql2-driver/view}
 * @see {@link https://adamcoster.com/blog/javascript-custom-errors}
 * @see {@link errors.js}
 */
class BaseDAO {
    /**
     * This constructor checks if the class is being instantiated directly.
     * @constructor
     */
    constructor() {
        if (new.target === BaseDAO) {
            throw new Error("BaseDAO cannot be instantiated directly.");
        }
    }

    /**
     * This protected method returns the shared MySQL connection pool.
     * @protected
     * @returns {Promise<import('mysql2/promise').Pool>}
     */
    async _db() {
        return getPool();
    }

    /**
     * This protected method runs a SQL query and maps failures to app errors.
     * @protected
     * @param {string} sql
     * @param {unknown[]} params
     * @param {object} [options]
     * @param {string} [options.conflictMessage] Message on ER_DUP_ENTRY
     * @param {object} [options.conflictDetails] Extra details for ConflictError
     * @param {string} [options.notFoundResource] Resource name when no row matched
     * @param {boolean} [options.suppressNotFound=false] When true, empty results do not throw NotFoundError
     * @returns {Promise<import('mysql2/promise').QueryResult>}
     * @throws {ConflictError|NotFoundError|DatabaseError}
     */
    async _query(sql, params = [], options = {}) {
        try {
            const db = await this._db();
            const result = await db.execute(sql, params);

            if (options.notFoundResource && !options.suppressNotFound) {
                const [payload] = result;

                if (Array.isArray(payload) && payload.length === 0) {
                    throw new NotFoundError(options.notFoundResource);
                }

                if (!Array.isArray(payload) && payload.affectedRows === 0) {
                    throw new NotFoundError(options.notFoundResource);
                }
            }

            return result;
        } catch (err) {
            if (err instanceof NotFoundError) {
                throw err;
            }

            if (err.code === "ER_DUP_ENTRY" && options.conflictMessage) {
                throw new ConflictError(
                    options.conflictMessage,
                    options.conflictDetails ?? null,
                );
            }

            throw new DatabaseError(err.message);
        }
    }

    /**
     * This protected method runs a transaction with a MySQL connection.
     * @pre caller shall not throw a generic Error. The caller is responsible for handling the errors and re-throwing them if necessary.
     * @protected
     * @param {function(import('mysql2/promise').PoolConnection, object): Promise<unknown>} work
     * @param {object} [options]
     * @param {boolean} [options.suppressNotFound=false] Passed to query helpers inside the transaction
     * @returns {Promise<unknown>} The result of the work
     * @throws {DatabaseError} On database failures
     * @throws {NotFoundError} If the transaction fails due to a not found error
     * @throws {ConflictError} If the transaction fails due to a conflict error
     * @throws {ValidationError} If the transaction fails due to a validation error
     * @throws {DatabaseError} If the transaction fails due to a non-database error
     */
    async _transaction(work, options = {}) {
        const db = await this._db();
        const conn = await db.getConnection();
        const queryOptions = {
            suppressNotFound: options.suppressNotFound ?? false,
        };
        try {
            await conn.beginTransaction();
            const result = await work(conn, queryOptions);
            await conn.commit();
            return result;
        } catch (err) {
            try {
                await conn.rollback();
            } catch (rollbackErr) {
                console.error(
                    "[BaseDAO] rollback failed:",
                    rollbackErr.message,
                );
            }

            // if error is not raised explicitly, throw a database error;
            // else, re-throw the error generated by the work function from the calling service
            if (
                !(
                    err instanceof NotFoundError ||
                    err instanceof ConflictError ||
                    err instanceof ValidationError
                )
            ) {
                throw new DatabaseError(err.message);
            } else {
                throw err;
            }
        } finally {
            conn.release();
        }
    }
}

export default BaseDAO;
